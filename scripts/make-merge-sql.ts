// Builds what the merge into the Main ERP takes from this schema (Step 9,
// docs/10-merge-guide.md), so it can never drift from prisma/schema.prisma:
//
//   merge/purchase-schema-block.prisma  the PURCHASE MODULE block to append to the Main ERP's
//                                       prisma/schema.prisma: every model and enum of this
//                                       schema except the standalone sign-in (its last section)
//   merge/purchase-module.sql           the numbered script that creates them in the ERP's
//                                       database, in the Main ERP's way (scripts/0146 for
//                                       Pigment): the PURCHASE value on "Role" before BEGIN,
//                                       then the tables in one transaction, additive and
//                                       idempotent, refusing a database that is not the ERP's or
//                                       holds part of the module, and one action_log row
//
// The DDL is Prisma's own (`prisma migrate diff --from-empty`), made idempotent, so
// `prisma migrate diff` against the Main ERP's schema stays clean once the script has run.
//
// Usage: npm run merge:sql   (re-run after any schema change; tests/purchase/merge.test.ts checks)
import { execSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

// The repository root: npm runs scripts there (here, and from scripts/purchase/ in the Main ERP).
const root = process.cwd();
const schema = readFileSync(join(root, "prisma/schema.prisma"), "utf8").replace(/\r\n/g, "\n");
const lines = schema.split("\n");

// The block: after the datasource, before the STANDALONE ONLY section (and its rule line).
const dsStart = lines.findIndex((l) => /^datasource\s+\w+\s*\{/.test(l));
const dsEnd = lines.findIndex((l, i) => i > dsStart && l.trim() === "}");
let standalone = lines.findIndex((l) => l.startsWith("// STANDALONE ONLY"));
if (dsStart < 0 || dsEnd < 0 || standalone < 0) throw new Error("schema.prisma: datasource or the STANDALONE ONLY section not found");
if (lines[standalone - 1]?.startsWith("// ---")) standalone -= 1;
const block = lines.slice(dsEnd + 1, standalone).join("\n").trim();
if (/model PurchaseLogin\b/.test(block)) throw new Error("the standalone sign-in leaked into the block");

const blockFile = `// ============================================================================
// PURCHASE MODULE (Procurement ERP, merged as the "purchase" module).
// Generated by the Procurement ERP's \`npm run merge:sql\` from its prisma/schema.prisma; do not
// edit by hand there, edit the module's schema and regenerate. Append this whole block at the
// foot of the Main ERP's prisma/schema.prisma, and add PURCHASE to enum Role (the script adds
// the database value). Every model is Purchase*, every table and enum type purchase_*; no
// relation leaves the module.
// ============================================================================

${block}
`;
writeFileSync(join(root, "merge/purchase-schema-block.prisma"), blockFile);

// Prisma's DDL for the block alone.
const tmp = mkdtempSync(join(tmpdir(), "purchase-merge-"));
let ddl: string;
try {
  const tmpSchema = join(tmp, "schema.prisma");
  writeFileSync(tmpSchema, `generator client {\n  provider = "prisma-client-js"\n}\n\ndatasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}\n\n${block}\n`);
  ddl = execSync(`npx prisma migrate diff --from-empty --to-schema-datamodel "${tmpSchema}" --script`, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).replace(/\r\n/g, "\n");
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

// Statements, one per ";" at a line end.
const statements: string[] = [];
let cur: string[] = [];
for (const l of ddl.split("\n")) {
  if (!cur.length && (l.trim() === "" || l.startsWith("--"))) continue;
  cur.push(l);
  if (l.trimEnd().endsWith(";")) {
    statements.push(cur.join("\n"));
    cur = [];
  }
}
if (cur.length) throw new Error(`unterminated statement: ${cur.join("\n")}`);

const types: string[] = [];
const tables: string[] = [];
const indexes: { name: string; table: string; unique: boolean }[] = [];
const fks: { name: string; table: string }[] = [];
let columns = 0;
const out: string[] = [];
for (const s of statements) {
  let m: RegExpExecArray | null;
  // The ERP's schema is there already; Prisma names it only because the diff starts from nothing.
  if (/^CREATE SCHEMA IF NOT EXISTS "public";$/.test(s.trim())) continue;
  if ((m = /^CREATE TYPE "([^"]+)" AS ENUM/.exec(s))) {
    types.push(m[1]);
    out.push(`DO $$ BEGIN\n  ${s}\nEXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
  } else if ((m = /^CREATE TABLE "([^"]+)" \(/.exec(s))) {
    tables.push(m[1]);
    columns += s.split("\n").filter((l) => /^\s+"[^"]+" /.test(l)).length;
    out.push(s.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS "));
  } else if ((m = /^CREATE (UNIQUE )?INDEX "([^"]+)" ON "([^"]+)"/.exec(s))) {
    indexes.push({ name: m[2], table: m[3], unique: !!m[1] });
    out.push(s.replace(/^CREATE (UNIQUE )?INDEX /, (_x, u) => `CREATE ${u ?? ""}INDEX IF NOT EXISTS `));
  } else if ((m = /^ALTER TABLE "([^"]+)" ADD CONSTRAINT "([^"]+)" FOREIGN KEY/.exec(s))) {
    fks.push({ table: m[1], name: m[2] });
    out.push(`DO $$ BEGIN\n  ${s}\nEXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
  } else {
    throw new Error(`unexpected statement in Prisma's DDL:\n${s}`);
  }
}
for (const t of tables) if (!t.startsWith("purchase_")) throw new Error(`table outside the namespace: ${t}`);
for (const t of types) if (!t.startsWith("purchase_")) throw new Error(`enum type outside the namespace: ${t}`);

const list = (xs: string[], per = 3) => {
  const rows: string[] = [];
  for (let i = 0; i < xs.length; i += per) rows.push("  " + xs.slice(i, i + per).join(", "));
  return rows.join(",\n");
};
const expected = [
  ...types.map((n) => `('type', '${n}')`),
  ...tables.map((n) => `('table', '${n}')`),
  ...indexes.map((x) => `('index', '${x.name}')`),
  ...fks.map((x) => `('constraint', '${x.name}')`),
];
const N = { types: types.length, tables: tables.length, indexes: indexes.length, fks: fks.length, columns };

const sql = `-- NNNN: the Purchase module — the PURCHASE value on "Role", and the module's
-- tables: ${N.types} purchase_* enum types and ${N.tables} purchase_* tables.
-- GENERATED by the Procurement ERP's \`npm run merge:sql\` (scripts/make-merge-sql.ts) from its
-- prisma/schema.prisma; the Prisma side is merge/purchase-schema-block.prisma, appended at the
-- foot of the Main ERP's schema, and the PURCHASE value of enum Role. Give the file the next free
-- number when it is merged (0148 was the last on main at e4d9eacf, 30-10-2026), and put that
-- number in for NNNN.
--
-- WHY. The Procurement ERP replaces the old ERPNext site's Buying → Purchase Order (shut down
-- November 2026) and joins the ERP as a module, the way Chromia, Lab and Pigment did: a capped
-- role, routes under /purchase and /api/purchase, its data in its own purchase_* tables
-- (docs/00-feasibility-and-plan.md, docs/10-merge-guide.md).
--
-- WHAT.
--   "Role" gains 'PURCHASE' (ADD VALUE IF NOT EXISTS, before BEGIN — see below).
--   ${N.types} enum types, ${N.tables} tables, ${N.columns} columns, ${N.indexes} indexes, ${N.fks} foreign keys, all
--   named purchase_*. The tables are the module's final shape (its migrations through
--   20261118204039_item_variants_and_hsn), less the standalone sign-in (purchase_logins), which
--   the ERP's users and roles replace.
--
-- THE MODULE DOES NOT START EMPTY. After this script the module's importer loads the old site's
-- final backup into these tables, once (\`npm run import:erpnext -- --target <this database's host>\`:
-- 3,217 POs on the 19-11-2026 backup, and every master they point at), reconciles the counts, and
-- \`npm run verify:erpnext\` proves the result read-only (docs/10-merge-guide.md, "Cut-over"). The
-- importer refuses a second load once anything is done in the module. Nothing here inserts data.
--
-- CONVENTIONS. Prisma's own DDL for the block (\`prisma migrate diff --from-empty\`), so
-- \`prisma migrate diff\` against the ERP's schema stays clean once this has run: TEXT ids
-- (cuid(), made by the app), NUMERIC(21,9) for money, quantities and rates as ERPNext stored
-- them, DATE for a calendar date, TIMESTAMP(3) for a moment (UTC), JSONB for the old record kept
-- whole (\`legacy\`); updated_at with no default (Prisma's @updatedAt stamps it); unique INDEXES,
-- not constraints; <table>_pkey, <table>_<cols>_key, <table>_<cols>_idx, <table>_<cols>_fkey.
-- NOTHING LEAVES THE MODULE: no foreign key points outside purchase_*, and no column names a
-- users.id. Who did what is kept by email, as the old site kept it.
--
-- THE ROLE VALUE AND THE TRANSACTION. PostgreSQL cannot USE an enum value in the transaction
-- that adds it. Nothing in this file uses 'PURCHASE', and nothing appended to it may. The ADD
-- VALUE stands BEFORE the BEGIN: run by psql it commits on its own; sent whole by \`prisma db
-- execute\` it commits with the rest. The logins are made afterwards, in Users & Roles.
--
-- Applied with:
--   npx prisma db execute --schema prisma/schema.prisma --file scripts/NNNN-purchase-module.sql
--   npx prisma generate
-- (NOT \`prisma db push\`.)
--
-- WHEN: BEFORE the code that reads these tables is deployed, or with it. Running it first is
-- safe: the code live today names neither the value nor the tables.
--
-- ADDITIVE AND IDEMPOTENT. ADD VALUE IF NOT EXISTS; types and foreign keys in DO …
-- duplicate_object blocks; CREATE TABLE / INDEX IF NOT EXISTS. No DROP, no ALTER of an existing
-- table or column, no UPDATE, no DELETE. The tables in one transaction: all of them or none.
-- Safe to run twice; the second run adds nothing and logs nothing.
--
-- REFUSES, changing nothing, when (checked before anything is created):
--   * "Role" or action_log is not there (this is not the ERP database);
--   * some of the module's ${N.tables} tables are there but not all of them: a part-made module is a
--     person's call. Compare it with merge/purchase-schema-block.prisma first
--     (\`prisma migrate diff --from-url … --to-schema-datamodel …\`).
--
-- Logged: one action_log row on the first run, naming what it added; later runs log only if
-- they add something.
--
-- CHECK (after):
--   SELECT enumlabel FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid
--    WHERE t.typname = 'Role' AND enumlabel = 'PURCHASE';
--     -- one row
--   SELECT count(*) FROM pg_type WHERE typname LIKE 'purchase\\_%' AND typtype = 'e';
--     -- ${N.types}
--   SELECT count(*) FROM information_schema.tables
--    WHERE table_schema = current_schema() AND table_name LIKE 'purchase\\_%';
--     -- ${N.tables}
--   SELECT count(*) FROM information_schema.columns
--    WHERE table_schema = current_schema() AND table_name LIKE 'purchase\\_%';
--     -- ${N.columns}
--   SELECT count(*) FROM pg_indexes
--    WHERE schemaname = current_schema() AND tablename LIKE 'purchase\\_%' AND indexname NOT LIKE '%\\_pkey';
--     -- ${N.indexes}
--   SELECT contype, count(*) FROM pg_constraint
--    WHERE conrelid::regclass::text LIKE 'purchase\\_%' AND contype IN ('f', 'p')
--    GROUP BY contype ORDER BY contype;
--     -- f ${N.fks}, p ${N.tables}
--   SELECT confrelid::regclass, count(*) FROM pg_constraint
--    WHERE contype = 'f' AND conrelid::regclass::text LIKE 'purchase\\_%'
--      AND confrelid::regclass::text NOT LIKE 'purchase\\_%' GROUP BY 1;
--     -- 0 rows: no foreign key leaves the module
--   SELECT summary FROM action_log WHERE payload->>'action' = 'purchase-module';
--     -- 1 row

-- ═══════════════════════════════ THE ROLE VALUE ═══════════════════════════════
ALTER TYPE "Role" ADD VALUE IF NOT EXISTS 'PURCHASE';

BEGIN;

-- Every table here is new; the only existing table touched is action_log, for one insert at the
-- end. If even that has to wait, give up after 5 s and roll back whole.
SET LOCAL lock_timeout = '5s';

-- ─────────────────────────── what this script makes ───────────────────────────
CREATE TEMP TABLE pm_expected (kind text, name text) ON COMMIT DROP;
INSERT INTO pm_expected VALUES
${list(expected, 2)};

CREATE TEMP TABLE pm_present (kind text, name text) ON COMMIT DROP;

-- ───────────────────────────── the preconditions ──────────────────────────────
DO $$
DECLARE have int;
BEGIN
  IF to_regtype('"Role"') IS NULL OR to_regclass('action_log') IS NULL THEN
    RAISE EXCEPTION 'purchase-module: "Role" or action_log is missing, so this is not the ERP database. Nothing was changed.';
  END IF;
  SELECT count(*) INTO have FROM pm_expected WHERE kind = 'table' AND to_regclass(name) IS NOT NULL;
  IF have > 0 AND have < ${N.tables} THEN
    RAISE EXCEPTION 'purchase-module: % of the module''s ${N.tables} tables are already there. A part-made module is a person''s call: compare the database with merge/purchase-schema-block.prisma first. Nothing was changed.', have;
  END IF;
  -- What is there before: what the log will not count as added.
  INSERT INTO pm_present
    SELECT kind, name FROM pm_expected
     WHERE (kind = 'type' AND to_regtype(name) IS NOT NULL)
        OR (kind IN ('table', 'index') AND to_regclass(name) IS NOT NULL)
        OR (kind = 'constraint' AND EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conname = name AND c.connamespace = current_schema()::regnamespace));
END $$;

-- ─────────────────────────────── the module ───────────────────────────────────
${out.join("\n\n")}

-- ─────────────────────────────────── the log ────────────────────────────────────
WITH added AS (
  SELECT e.kind, e.name AS what FROM pm_expected e
   WHERE NOT EXISTS (SELECT 1 FROM pm_present p WHERE p.kind = e.kind AND p.name = e.name)
)
INSERT INTO action_log (id, actor, kind, model, summary, payload)
SELECT gen_random_uuid()::text, 'schema change (scripts/NNNN)', 'edit', 'PurchaseOrder',
       format('The Purchase module (scripts/NNNN): %s.',
              CASE WHEN count(*) = 0 THEN 'all of it already in place'
                   ELSE format('added %s of ${N.types} enum types, %s of ${N.tables} tables, %s of ${N.indexes} indexes and %s of ${N.fks} foreign keys, all named purchase_*; nothing that existed was changed',
                               count(*) FILTER (WHERE kind = 'type'),
                               count(*) FILTER (WHERE kind = 'table'),
                               count(*) FILTER (WHERE kind = 'index'),
                               count(*) FILTER (WHERE kind = 'constraint')) END),
       jsonb_build_object('action', 'purchase-module', 'added', COALESCE(jsonb_agg(what ORDER BY what), '[]'::jsonb))
FROM added
HAVING count(*) > 0
    OR NOT EXISTS (SELECT 1 FROM action_log WHERE payload->>'action' = 'purchase-module');

COMMIT;

-- ───────────────────────────────── UNDO ─────────────────────────────────────────
-- By hand, and only after the code that reads these is rolled back. It throws away every PO,
-- master and history line in the module — export them first.
--
-- BEGIN;
-- DROP TABLE IF EXISTS
${list(tables.slice().reverse()).replace(/^/gm, "--  ")}
--   CASCADE;
-- DROP TYPE IF EXISTS
${list(types).replace(/^/gm, "--  ")};
-- COMMIT;
--
-- PostgreSQL has no DROP VALUE for an enum. An unused 'PURCHASE' is inert: re-role every login
-- holding it (SELECT id, email FROM users WHERE role = 'PURCHASE' OR alt_role = 'PURCHASE';) and
-- leave the value in place.
`;
writeFileSync(join(root, "merge/purchase-module.sql"), sql);
console.log(`merge/purchase-schema-block.prisma and merge/purchase-module.sql: ${N.types} enum types, ${N.tables} tables, ${N.columns} columns, ${N.indexes} indexes, ${N.fks} foreign keys.`);
