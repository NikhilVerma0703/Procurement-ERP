"""Save every captured form's layout as the forms render it (Phase II, owner 21-11-2026).

The old site's form definitions as it served them on 21-11-2026 (data/erpnext-live/live-meta-*.json,
frappe.desk.form.load.getdoctype: the standard fields with the add-on's custom fields placed and
the property setters applied, in the final order). Once the site is gone these files are the
reference for the module's forms: field order, labels, types, tabs, sections, columns,
show/hide conditions, required and read-only flags, list columns and standard filters.

Writes src/lib/purchase/doc/layouts/<doctype-slug>.json, one per DocType (child tables included),
and src/lib/purchase/doc/layouts/index.ts mapping each DocType name to its layout.

Usage: python -I extract_layouts.py <live-meta.json> <out dir>
"""
import json
import os
import re
import sys

KEEP = [
    ("fieldname", "fieldname"), ("label", "label"), ("fieldtype", "fieldtype"), ("options", "options"),
    ("hidden", "hidden"), ("reqd", "reqd"), ("read_only", "readOnly"), ("depends_on", "dependsOn"),
    ("mandatory_depends_on", "mandatoryDependsOn"), ("read_only_depends_on", "readOnlyDependsOn"),
    ("collapsible", "collapsible"), ("collapsible_depends_on", "collapsibleDependsOn"), ("bold", "bold"),
    ("in_list_view", "inListView"), ("in_standard_filter", "inStandardFilter"), ("columns", "columns"),
    ("precision", "precision"), ("description", "description"), ("allow_on_submit", "allowOnSubmit"),
    ("default", "default"), ("fetch_from", "fetchFrom"), ("print_hide", "printHide"), ("non_negative", "nonNegative"), ("permlevel", "permlevel"),
    # Frappe's Standard print (docs/15, X3, 26-11-2026).
    ("print_hide_if_no_value", "printHideIfNoValue"), ("print_width", "printWidth"),
    # Duplicate and Amend leave these out (copy_doc; docs/15, 26-11-2026).
    ("no_copy", "noCopy"),
]
FLAGS = {"hidden", "reqd", "read_only", "collapsible", "bold", "in_list_view", "in_standard_filter", "allow_on_submit", "print_hide", "non_negative", "print_hide_if_no_value", "no_copy"}


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main(src, out_dir):
    bundle = json.load(open(src, encoding="utf-8"))
    os.makedirs(out_dir, exist_ok=True)
    seen = {}
    for res in bundle["doctypes"].values():
        for doc in res.get("docs", []):
            if doc.get("doctype") != "DocType" or doc["name"] in seen:
                continue
            fields = []
            for f in doc.get("fields", []):
                row = {}
                for src_key, key in KEEP:
                    v = f.get(src_key)
                    if src_key in FLAGS:
                        if v in (1, "1", True):
                            row[key] = True
                    elif v not in (None, "", 0, "0"):
                        row[key] = v
                fields.append(row)
            layout = {
                "doctype": doc["name"],
                "module": doc.get("module"),
                "istable": bool(doc.get("istable")),
                "issingle": bool(doc.get("issingle")),
                "isSubmittable": bool(doc.get("is_submittable")),
                "autoname": doc.get("autoname") or None,
                "showTitleFieldInLink": bool(doc.get("show_title_field_in_link")),
                "titleField": doc.get("title_field") or None,
                "sortField": doc.get("sort_field") or "modified",
                "sortOrder": doc.get("sort_order") or "DESC",
                "searchFields": doc.get("search_fields") or None,
                "defaultPrintFormat": doc.get("default_print_format") or None,
                "fields": fields,
            }
            seen[doc["name"]] = slug(doc["name"])
            with open(os.path.join(out_dir, f"{slug(doc['name'])}.json"), "w", encoding="utf-8", newline="\n") as fh:
                json.dump(layout, fh, indent=1, ensure_ascii=False)
                fh.write("\n")
    names = sorted(seen)
    lines = [
        "// GENERATED by scripts/analysis/extract_layouts.py from the old site's live form definitions",
        f"// ({os.path.basename(src)}): do not edit by hand. Phase II, owner 21-11-2026.",
        "import type { DoctypeLayout } from \"../layout\";",
    ]
    for i, n in enumerate(names):
        lines.append(f"import l{i} from \"./{seen[n]}.json\";")
    lines.append("")
    lines.append("/** Every captured DocType's layout, by DocType name. */")
    lines.append("export const LAYOUTS: Record<string, DoctypeLayout> = {")
    for i, n in enumerate(names):
        lines.append(f"  {json.dumps(n)}: l{i} as DoctypeLayout,")
    lines.append("};")
    with open(os.path.join(out_dir, "index.ts"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(names)} layouts -> {out_dir}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
